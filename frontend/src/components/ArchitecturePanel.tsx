import { LayoutGrid, List } from "lucide-react";
import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { api } from "../api/client";
import type { ArchitectureModel, Smell } from "../api/types";
import { ArchitectureDiagram, ExternalDependencyBoundary } from "@/components/architecture/ArchitectureDiagram";
import { ArchitectureList } from "@/components/architecture/ArchitectureList";
import { ComponentInspector } from "@/components/architecture/ComponentInspector";
import { ConfidenceBadge } from "@/components/evidence/ConfidenceBadge";
import { SectionLabel } from "@/components/evidence/SectionLabel";
import { aggregateExternalDependencies, deriveLayers, summarize } from "@/lib/architectureModel";
import { confidenceLabel } from "@/lib/flowModel";
import { useInvestigation } from "@/lib/investigation";
import { cn } from "@/lib/utils";

type ViewMode = "diagram" | "list";

function StatTile({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <strong className="font-mono text-xl text-(--text) tabular-nums">{value}</strong>
      <span className="block text-[0.65rem] font-medium tracking-wide text-(--text-faint) uppercase">{label}</span>
    </div>
  );
}

export function ArchitecturePanel({ repoId }: { repoId: string }) {
  const { focus } = useInvestigation();
  const consumedFocusRef = useRef(false);

  const [model, setModel] = useState<ArchitectureModel | null>(null);
  const [smells, setSmells] = useState<Smell[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [view, setView] = useState<ViewMode>("diagram");
  const [selectedId, setSelectedId] = useState<string | null>(null);

  useEffect(() => {
    setModel(null);
    setError(null);
    setSelectedId(null);
    consumedFocusRef.current = false;
    api
      .getArchitecture(repoId)
      .then(setModel)
      .catch((err) => setError(err instanceof Error ? err.message : "Failed to reconstruct architecture."));
    api.getSmells(repoId).then(setSmells).catch(() => setSmells([]));
  }, [repoId]);

  useEffect(() => {
    if (consumedFocusRef.current || !focus?.componentId || !model) return;
    if (!model.components.some((c) => c.id === focus.componentId)) return;
    consumedFocusRef.current = true;
    setSelectedId(focus.componentId);
  }, [focus, model]);

  const handleSelect = useCallback((id: string | null) => setSelectedId(id), []);

  const nameById = useMemo(() => new Map((model?.components ?? []).map((c) => [c.id, c.name])), [model]);
  const selectedComponent = model?.components.find((c) => c.id === selectedId) ?? null;

  const layers = useMemo(() => (model ? deriveLayers(model.components) : []), [model]);
  const externalDeps = useMemo(() => (model ? aggregateExternalDependencies(model.components) : []), [model]);
  const summary = useMemo(() => (model ? summarize(model, layers, externalDeps) : null), [model, layers, externalDeps]);
  const selectedLayer = selectedComponent ? (layers.find((l) => l.componentIds.includes(selectedComponent.id)) ?? null) : null;

  const findingsByComponent = useMemo(() => {
    if (!model || !smells) return new Map<string, Smell[]>();
    const map = new Map<string, Smell[]>();
    for (const component of model.components) {
      const fileSet = new Set(component.files);
      const matched = smells.filter((s) => s.affected.some((a) => fileSet.has(a.file_path)));
      if (matched.length > 0) map.set(component.id, matched);
    }
    return map;
  }, [model, smells]);

  if (error) return <p className="text-sm text-(--bad)">{error}</p>;
  if (!model)
    return (
      <div className="flex flex-col gap-2">
        {[0, 1, 2, 3].map((i) => (
          <div key={i} className="h-14 animate-pulse rounded-md bg-(--bg-sunken)" />
        ))}
      </div>
    );
  if (model.components.length === 0)
    return <p className="text-sm text-(--text-faint)">No components could be reconstructed for this repository.</p>;

  return (
    <div className={cn("min-w-0", selectedComponent && "lg:pr-[336px]")}>
      <div className="min-w-0">
        <SectionLabel index="01">Reconstructed system</SectionLabel>
        <p className="mb-5 max-w-2xl text-sm text-(--text-soft)">
          Reconstructed from the knowledge graph's directory structure, call relationships, naming conventions, and
          import evidence — not generated by an LLM. Every layer and component is a derived grouping; select one to
          see the exact evidence behind it.
        </p>

        {summary && (
          <div className="mb-6 flex flex-wrap gap-x-8 gap-y-3 rounded-lg border border-(--border) bg-(--bg-raised) p-4">
            <StatTile label="Confidence" value={confidenceLabel(summary.averageConfidence)} />
            <StatTile label="Layers" value={String(summary.layerCount)} />
            <StatTile label="Runtime components" value={String(summary.runtimeComponentCount)} />
            <StatTile label="Supporting components" value={String(summary.supportingComponentCount)} />
            <StatTile label="External dependencies" value={String(summary.externalDependencyCount)} />
          </div>
        )}

        <div className="mb-3 flex justify-end">
          <div className="inline-flex overflow-hidden rounded-md border border-(--border)">
            <button
              onClick={() => setView("diagram")}
              aria-pressed={view === "diagram"}
              className={cn(
                "flex items-center gap-1.5 px-2.5 py-1.5 text-xs font-medium",
                view === "diagram" ? "bg-(--accent-soft) text-(--accent-text)" : "bg-(--bg-raised) text-(--text-faint)",
              )}
            >
              <LayoutGrid className="size-3.5" /> Diagram
            </button>
            <button
              onClick={() => setView("list")}
              aria-pressed={view === "list"}
              className={cn(
                "flex items-center gap-1.5 border-l border-(--border) px-2.5 py-1.5 text-xs font-medium",
                view === "list" ? "bg-(--accent-soft) text-(--accent-text)" : "bg-(--bg-raised) text-(--text-faint)",
              )}
            >
              <List className="size-3.5" /> List
            </button>
          </div>
        </div>

        {view === "diagram" ? (
          <>
            <ArchitectureDiagram
              layers={layers}
              components={model.components}
              relationships={model.relationships}
              selectedId={selectedId}
              onSelect={handleSelect}
            />
            <ExternalDependencyBoundary dependencies={externalDeps} />
          </>
        ) : (
          <ArchitectureList components={model.components} selectedId={selectedId} onSelect={handleSelect} />
        )}

        {model.relationships.length > 0 && (
          <div className="mt-8">
            <h4 className="mb-2 text-[0.72rem] font-semibold tracking-wide text-(--text-faint) uppercase">
              Component relationships
            </h4>
            <ul className="flex flex-col gap-1.5">
              {model.relationships.slice(0, 12).map((r, i) => (
                <li
                  key={i}
                  title={r.evidence.join("\n")}
                  className="flex flex-wrap items-center gap-2 rounded-md border border-(--border) bg-(--bg-raised) px-3 py-2 text-xs"
                >
                  <code className="text-(--text)">{nameById.get(r.source_id) ?? r.source_id}</code>
                  <span className="text-(--text-faint)">→</span>
                  <code className="text-(--text)">{nameById.get(r.target_id) ?? r.target_id}</code>
                  <span className="ml-auto font-mono text-(--text-faint)">
                    {r.call_count} call{r.call_count === 1 ? "" : "s"}
                  </span>
                  <ConfidenceBadge label={r.confidence_label} />
                </li>
              ))}
            </ul>
          </div>
        )}

        {model.detection_notes.length > 0 && (
          <ul className="mt-6 flex flex-col gap-1 border-t border-(--border) pt-4">
            {model.detection_notes.map((n, i) => (
              <li key={i} className="text-xs text-(--text-faint) italic">
                {n}
              </li>
            ))}
          </ul>
        )}
      </div>

      <ComponentInspector
        component={selectedComponent}
        layer={selectedLayer}
        nameById={nameById}
        relationships={model.relationships}
        findings={selectedComponent ? (findingsByComponent.get(selectedComponent.id) ?? []) : []}
        onClose={() => setSelectedId(null)}
      />
    </div>
  );
}
