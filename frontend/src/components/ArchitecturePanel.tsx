import { useEffect, useState } from "react";
import { api } from "../api/client";
import type { ArchitectureComponent, ArchitectureModel, ComponentRole } from "../api/types";

const ROLE_LABELS: Record<ComponentRole, string> = {
  api: "API layer",
  service: "Service layer",
  data_access: "Data access",
  external_integration: "External integration",
  model: "Model / schema",
  test: "Tests",
  other: "Other",
};

function ConfidencePill({ label }: { label: string }) {
  return <span className={`confidence-pill confidence-${label.toLowerCase()}`}>{label}</span>;
}

function ComponentCard({
  component,
  expanded,
  onToggle,
}: {
  component: ArchitectureComponent;
  expanded: boolean;
  onToggle: () => void;
}) {
  return (
    <div className={`arch-component role-${component.role}`}>
      <button className="arch-component-header" onClick={onToggle}>
        <div className="arch-component-title">
          <span className="arch-role-pill">{ROLE_LABELS[component.role] ?? component.role}</span>
          <code>{component.name}</code>
        </div>
        <div className="arch-component-meta">
          <span className="hint">
            {component.file_count} file{component.file_count === 1 ? "" : "s"}, {component.symbol_count} symbol
            {component.symbol_count === 1 ? "" : "s"}
          </span>
          <ConfidencePill label={component.confidence_label} />
        </div>
      </button>
      {expanded && (
        <div className="arch-component-body">
          <ul className="arch-evidence">
            {component.evidence.map((e, i) => (
              <li key={i}>{e}</li>
            ))}
          </ul>
          <p className="arch-files-label">Files ({component.files.length}):</p>
          <ul className="arch-files">
            {component.files.slice(0, 12).map((f) => (
              <li key={f}>
                <code>{f}</code>
              </li>
            ))}
            {component.files.length > 12 && <li className="dependent-more">…and {component.files.length - 12} more</li>}
          </ul>
        </div>
      )}
    </div>
  );
}

export function ArchitecturePanel({ repoId }: { repoId: string }) {
  const [model, setModel] = useState<ArchitectureModel | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [expandedId, setExpandedId] = useState<string | null>(null);

  useEffect(() => {
    setModel(null);
    setError(null);
    api
      .getArchitecture(repoId)
      .then(setModel)
      .catch((err) => setError(err instanceof Error ? err.message : "Failed to reconstruct architecture."));
  }, [repoId]);

  if (error) return <p className="form-error">{error}</p>;
  if (!model) return <p className="hint">Reconstructing architecture…</p>;
  if (model.components.length === 0) return <p className="hint">No components could be reconstructed for this repository.</p>;

  const nameById = new Map(model.components.map((c) => [c.id, c.name]));

  return (
    <div className="arch-panel">
      <p className="arch-intro">
        Reconstructed from the knowledge graph's directory structure, call relationships, and naming conventions —
        not generated by the AI. Click a component to see the evidence behind it.
      </p>

      <div className="arch-components">
        {model.components.map((c) => (
          <ComponentCard
            key={c.id}
            component={c}
            expanded={expandedId === c.id}
            onToggle={() => setExpandedId(expandedId === c.id ? null : c.id)}
          />
        ))}
      </div>

      {model.relationships.length > 0 && (
        <div className="arch-relationships">
          <h4>Component relationships</h4>
          <ul className="arch-relationship-list">
            {model.relationships.slice(0, 20).map((r, i) => (
              <li key={i} title={r.evidence.join("\n")}>
                <code>{nameById.get(r.source_id) ?? r.source_id}</code>
                <span className="arch-rel-arrow">→</span>
                <code>{nameById.get(r.target_id) ?? r.target_id}</code>
                <span className="arch-rel-count">{r.call_count} call{r.call_count === 1 ? "" : "s"}</span>
                <ConfidencePill label={r.confidence_label} />
              </li>
            ))}
          </ul>
        </div>
      )}

      <ul className="detection-notes">
        {model.detection_notes.map((n, i) => (
          <li key={i}>{n}</li>
        ))}
      </ul>
    </div>
  );
}
